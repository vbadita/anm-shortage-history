#!/usr/bin/env bash
# Sync Cloudflare's published IP ranges into
#   1. firewalld ipsets cloudflare-v4/-v6: only Cloudflare may connect to :443
#      (otherwise anyone can hit the origin IP directly and bypass Cloudflare's WAF/DDoS layer)
#   2. /etc/nginx/conf.d/cloudflare-realip.conf: trust CF-Connecting-IP only from those ranges
# Idempotent; safe to run from a weekly timer. Run as root.
set -euo pipefail
v4="$(curl -fsS --retry 3 https://www.cloudflare.com/ips-v4)"
v6="$(curl -fsS --retry 3 https://www.cloudflare.com/ips-v6)"
[ "$(wc -l <<<"$v4")" -ge 10 ] || { echo "suspiciously short ips-v4 list, aborting" >&2; exit 1; }

sync_ipset() {  # name family entries
  local name=$1 family=$2 entries=$3
  # (not `-q --info-ipset`: that combination is a usage error, exit 2, which reads as "missing")
  firewall-cmd --permanent --get-ipsets | tr ' ' '\n' | grep -qx "$name" \
    || firewall-cmd -q --permanent --new-ipset="$name" --type=hash:net --option=family="$family"
  for e in $(firewall-cmd --permanent --ipset="$name" --get-entries); do
    firewall-cmd -q --permanent --ipset="$name" --remove-entry="$e"
  done
  for e in $entries; do firewall-cmd -q --permanent --ipset="$name" --add-entry="$e"; done
}
sync_ipset cloudflare-v4 inet  "$v4"
sync_ipset cloudflare-v6 inet6 "$v6"
for fam in ipv4:cloudflare-v4 ipv6:cloudflare-v6; do
  rule="rule family=${fam%%:*} source ipset=${fam##*:} port port=443 protocol=tcp accept"
  firewall-cmd -q --permanent --query-rich-rule="$rule" || firewall-cmd -q --permanent --add-rich-rule="$rule"
done
firewall-cmd -q --reload

{
  echo "# Generated by update-cloudflare-ips.sh on $(date -u +%FT%TZ). Do not edit."
  for e in $v4 $v6; do echo "set_real_ip_from $e;"; done
  echo "real_ip_header CF-Connecting-IP;"
} > /etc/nginx/conf.d/cloudflare-realip.conf
nginx -t -q && systemctl reload nginx 2>/dev/null || true
echo "cloudflare-v4: $(wc -w <<<"$v4") ranges, cloudflare-v6: $(wc -w <<<"$v6") ranges"
