#!/usr/bin/env bash
# Regenerate app/requirements.txt and app/requirements-dev.txt from the *.in files.
# Resolves in a FRESH venv and freezes EVERYTHING installed: no hand-maintained
# package list (a hand-written allow-list once dropped opentelemetry-api, and the
# --no-deps Docker install only failed at runtime).
set -euo pipefail
cd "$(dirname "$0")/../app"
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
fresh() { python3.12 -m venv "$tmp/$1" && "$tmp/$1/bin/pip" install -q --upgrade pip==25.3; }

fresh run
"$tmp/run/bin/pip" install -q -r requirements.in -c constraints.txt
"$tmp/run/bin/pip" check
{ echo "# Generated by scripts/lock.sh from requirements.in + constraints.txt. Do not edit."
  "$tmp/run/bin/pip" freeze --all --exclude pip; } > requirements.txt

fresh dev
"$tmp/dev/bin/pip" install -q -r requirements.txt -r requirements-dev.in -c constraints.txt
"$tmp/dev/bin/pip" check
{ echo "# Generated by scripts/lock.sh. Do not edit."; echo "-r requirements.txt"
  "$tmp/dev/bin/pip" freeze --all --exclude pip | grep -vxFf <(grep -v '^#' requirements.txt); } > requirements-dev.txt
echo "runtime: $(grep -vc '^#' requirements.txt) packages, dev-only: $(grep -vcE '^(#|-r)' requirements-dev.txt)"
